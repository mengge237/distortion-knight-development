namespace MutationChess.Core
{
    /// <summary>
    /// 药水名称枚举。
    /// 参考杀戮尖塔经典药水命名，契合本项目的字段系统。
    /// </summary>
    public enum PotionName
    {
        // === 通用基础药水（参考杀戮尖塔基础药水）===
        能量药水,       // Energy Potion: 获得2能量
        抽牌药水,       // Draw Potion: 抽3张牌
        力量药水,       // Strength Potion: 获得2力量
        盾药水,         // Block Potion: 获得12格挡
        回复药水,       // Blood Potion: 回复8血量
        净化药水,       // Swift Potion: 移除玩家debuff

        // === 鲜血字段药水 ===
        血怒药水,       // 本回合所有卡牌可使用血量转换为能量字段
        纯血药水,       // 本回合血量转换公式为1血=1能量
        鲜血共鸣药水,   // 回复20血，下回合失去3力量

        // === 寒霜字段药水 ===
        冰封药水,       // 本回合格挡转换公式为1挡=1能量
        寒霜共鸣药水,   // 获得20格挡，下回合失去3敏捷
        永冻药水,       // 本回合受到的伤害减半，下回合无法获得格挡

        // === 腐化字段药水 ===
        腐化释放药水,   // 本回合所有卡牌不消耗能量
        黑暗契约药水,   // 消耗手牌全部卡牌，每张获1能量

        // === 字段联动药水 ===
        粘液净化药水,   // 触发手牌中所有粘液卡效果
        不舍回响药水,   // 从弃牌堆抽出2张不舍卡牌
        联动共鸣药水,   // 本回合所有字段共鸣效果触发两次

        // === 发现药水 ===
        发现药水,       // 发现一张卡牌加入卡组
        洞察药水,       // 查看卡牌堆顶5张卡牌
    }
}
